import qrcode from 'qrcode-generator';
import { useMemo } from 'react';
import './remote.css';

/** A QR code drawn as one SVG path, a module per unit, with the quiet zone it needs to scan. */
export function QrCode({ text, label = 'QR code for the remote' }: { text: string; label?: string }) {
  const { size, path } = useMemo(() => {
    const qr = qrcode(0, 'M');
    qr.addData(text);
    qr.make();
    const count = qr.getModuleCount();
    let d = '';
    for (let row = 0; row < count; row++) {
      for (let col = 0; col < count; col++) {
        if (qr.isDark(row, col)) d += `M${col + 4} ${row + 4}h1v1h-1z`;
      }
    }
    return { size: count + 8, path: d };
  }, [text]);

  return (
    <svg className="pairing-code" viewBox={`0 0 ${size} ${size}`} role="img" aria-label={label} shapeRendering="crispEdges">
      <rect width={size} height={size} fill="#fff" />
      <path d={path} fill="#000" />
    </svg>
  );
}
